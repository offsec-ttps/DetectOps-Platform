import { NextRequest, NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import {
  getGitHubCredentials,
  getDefaultGitHubOwner,
  ensureRepository,
  pushFileToBranchAndCreatePR,
  createIssue,
  createProjectV2,
  generateMarkdownReport,
  generateIssueBody,
} from "@/lib/github";
import { logEvent } from "@/lib/event-log";
import { isSafeSegment } from "@/lib/build-forge/validate";
import { getSessionUser } from "@/lib/auth";

export async function POST(req: NextRequest, { params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const pushStart = Date.now();
  const sessionUser = await getSessionUser().catch(() => null);
  const body = await req.json().catch(() => ({}));
  const repoName: string = body.repoName || "detection-reports";
  const createProject: boolean = body.createProject || false;

  // Get GitHub credentials (the git integration)
  const creds = await getGitHubCredentials();
  if (!creds) {
    return NextResponse.json({
      error: "GitHub integration not configured. Go to Integrations > GitHub Actions and add your Personal Access Token.",
    }, { status: 400 });
  }

  // Owner comes from the request, else is resolved from the git integration
  // (configured owner/org, or the token's authenticated login) — so push works
  // straight off the integration with no manual owner entry.
  const owner: string = body.owner || await getDefaultGitHubOwner();
  if (!owner) {
    return NextResponse.json({ error: "Could not determine a GitHub owner from the integration. Add an owner/org, or check the token." }, { status: 400 });
  }
  // owner/repoName are interpolated into GitHub API paths with the server token.
  if (!isSafeSegment(owner) || !isSafeSegment(repoName)) {
    return NextResponse.json({ error: "invalid owner or repoName" }, { status: 400 });
  }

  // Fetch report
  const report = await prisma.detectionReport.findUnique({
    where: { id },
    include: { simulations: { orderBy: { order: "asc" } } },
  });
  if (!report) return NextResponse.json({ error: "Report not found" }, { status: 404 });

  const results: Record<string, string> = {};
  const errors: string[] = [];

  try {
    // 1. Ensure repository exists
    const repo = await ensureRepository(creds.token, owner, repoName);
    results.repoUrl = repo.url;
    results.repoCreated = repo.created ? "yes" : "no";

    // 2. Generate and push markdown report
    const slug = report.name.toLowerCase().replace(/[^a-z0-9]+/g, "_").replace(/^_|_$/g, "");
    const filePath = `reports/${slug}.md`;
    const markdown = generateMarkdownReport({
      ...report,
      startDate: report.startDate?.toISOString() || null,
      endDate: report.endDate?.toISOString() || null,
      simulations: report.simulations.map((s) => ({
        description: s.description,
        output: s.output,
        order: s.order,
      })),
    });

    // 2b. Create issue body referencing the report (before PR so we can link)
    const reportGhUrl = `https://github.com/${owner}/${repoName}/blob/main/${filePath}`;
    const issueBody = generateIssueBody(
      {
        ...report,
        startDate: report.startDate?.toISOString() || null,
        endDate: report.endDate?.toISOString() || null,
        simulations: report.simulations.map((s) => ({
          description: s.description, output: s.output, order: s.order,
        })),
      },
      reportGhUrl
    );

    // 3. Create GitHub Issue for tracking
    const issue = await createIssue(
      creds.token, owner, repoName,
      `${slug}#${report.githubIssueNumber || "new"}`,
      issueBody,
      ["detection-report", report.severity, report.platform || "general"].filter(Boolean)
    );
    results.issueUrl = issue.url;
    results.issueNumber = String(issue.number);

    // 4. Push to branch and create PR (enterprise review workflow)
    const prBody = `## Detection Report: ${report.name}

Closes #${issue.number}

### Summary
- **Severity:** ${report.severity}
- **Platform:** ${report.platform || "N/A"}
- **Status:** ${report.status}
- **Techniques:** ${techniqueListFromQuery(report.detectionQuery)}
- **Simulations:** ${report.simulations.length}

### Changes
- Adds/updates detection report: \`${filePath}\`

### Review Checklist
- [ ] Detection query syntax verified
- [ ] Device coverage validated
- [ ] False positive assessment reviewed
- [ ] Simulation output reviewed
- [ ] Observations and recommendations reviewed

> Auto-generated by DetectOps — requires human review before merge.
`;

    const pr = await pushFileToBranchAndCreatePR(
      creds.token, owner, repoName, filePath, markdown,
      `docs: add detection report — ${report.name}`,
      `[Detection Report] ${report.name}`,
      prBody
    );
    results.reportUrl = pr.fileUrl;
    results.prUrl = pr.prUrl;
    results.prNumber = String(pr.prNumber);
    results.branchName = pr.branchName;

    // 5. Optionally create GitHub Project
    if (createProject) {
      try {
        const project = await createProjectV2(creds.token, owner, `Detection Reports — ${repoName}`);
        results.projectUrl = project.url;
      } catch (err) {
        errors.push(`Project creation: ${err instanceof Error ? err.message : String(err)}`);
      }
    }

    // 6. Update report record with GitHub URLs
    await prisma.detectionReport.update({
      where: { id },
      data: {
        githubReportUrl: results.prUrl || results.reportUrl || "",
        githubIssueUrl: results.issueUrl || "",
        githubIssueNumber: issue.number,
        githubProjectUrl: results.projectUrl || report.githubProjectUrl,
        githubPushedAt: new Date(),
      },
    });

    void logEvent({
      category: "report", action: "report.github_push",
      actor: sessionUser?.email || "anonymous", status: "ok",
      targetType: "report", targetId: id,
      durationMs: Date.now() - pushStart,
      message: `${owner}/${repoName} PR #${results.prNumber || "?"}`,
      details: {
        owner, repoName, prNumber: Number(results.prNumber || 0),
        prUrl: results.prUrl, issueUrl: results.issueUrl, branch: results.branchName,
        errorsCount: errors.length,
      },
    });

    return NextResponse.json({
      success: true,
      ...results,
      errors: errors.length > 0 ? errors : undefined,
    });
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    void logEvent({
      category: "report", action: "report.github_push",
      actor: sessionUser?.email || "anonymous", status: "error",
      targetType: "report", targetId: id,
      durationMs: Date.now() - pushStart,
      message: msg, errorMessage: msg,
      details: { owner, repoName },
    });
    return NextResponse.json({ success: false, error: msg, ...results }, { status: 500 });
  }
}

function techniqueListFromQuery(query: string): string {
  const matches = query.match(/T\d{4}(\.\d{3})?/gi);
  return matches ? [...new Set(matches)].join(", ") : "N/A";
}
