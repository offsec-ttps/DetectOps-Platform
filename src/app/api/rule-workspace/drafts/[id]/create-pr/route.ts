/**
 * POST /api/rule-workspace/drafts/[id]/create-pr
 *
 * Phase 7 — promote a Rule Workspace draft to a pull request against the
 * analyst's internal detection repository.
 *
 * Body:
 *   {
 *     owner:      "your-org",
 *     repo:       "detection-rules-internal",
 *     baseBranch: "main",                 // optional, default "main"
 *     filePath:   "rules/sigma/...yml",   // optional, derived from draft if absent
 *   }
 *
 * Notes / safety:
 *   - This is purely additive. It uses the existing GitHub helper that the
 *     platform already ships (pushFileToBranchAndCreatePR). Production
 *     deployment paths and reviewer workflows are unchanged.
 *   - We never overwrite the draft on success — we only stamp the draft row
 *     with prNumber/prUrl/prBranch/prRepo and flip status to "pr_open".
 *   - If credentials are missing or the call fails, the draft is left
 *     untouched and we return an actionable error.
 */

import { NextRequest, NextResponse } from "next/server";
import { prisma } from "@/lib/prisma";
import { getGitHubCredentials, pushFileToBranchAndCreatePR } from "@/lib/github";
import { logWorkspaceAudit } from "@/lib/rule-workspace/audit";
import { isSafeSegment, isSafeBranch } from "@/lib/build-forge/validate";

function extensionFor(language: string): string {
  switch ((language || "").toLowerCase()) {
    case "sigma":      return "yml";
    case "kql":        return "kql";
    case "spl":        return "spl";
    case "yara-l":     return "yaral";
    case "python":     return "py";
    case "falco-yaml": return "yaml";
    case "wazuh-xml":  return "xml";
    case "elastic":
    case "kuery":      return "toml";
    default:           return "txt";
  }
}

function defaultPath(draftId: string, title: string, language: string): string {
  const slug = title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60) || "untitled";
  const ext = extensionFor(language);
  return `rules/drafts/${slug}-${draftId.slice(0, 8)}.${ext}`;
}

export async function POST(req: NextRequest, ctx: { params: Promise<{ id: string }> }) {
  const { id } = await ctx.params;
  const draft = await prisma.ruleDraft.findUnique({ where: { id } });
  if (!draft) return NextResponse.json({ error: "draft not found" }, { status: 404 });
  if (draft.status === "pr_open" || draft.status === "merged") {
    return NextResponse.json({ error: `draft is already ${draft.status}`, prUrl: draft.prUrl }, { status: 409 });
  }

  const body = await req.json().catch(() => ({}));
  const { owner, repo, baseBranch, filePath: filePathOverride } = body as {
    owner?: string; repo?: string; baseBranch?: string; filePath?: string;
  };
  if (!owner || !repo) {
    return NextResponse.json({ error: "owner and repo are required" }, { status: 400 });
  }
  // These are interpolated into GitHub API paths with the server token.
  if (!isSafeSegment(owner) || !isSafeSegment(repo) || (baseBranch && !isSafeBranch(baseBranch))) {
    return NextResponse.json({ error: "invalid owner / repo / baseBranch" }, { status: 400 });
  }
  if (filePathOverride !== undefined && (typeof filePathOverride !== "string" || !/^[A-Za-z0-9._\/-]{1,200}$/.test(filePathOverride) || filePathOverride.split("/").some((seg) => seg === "" || seg === "." || seg === ".."))) {
    return NextResponse.json({ error: "invalid filePath" }, { status: 400 });
  }

  const creds = await getGitHubCredentials();
  if (!creds) {
    return NextResponse.json({
      error: "GitHub integration is not configured",
      hint: "Set up the GitHub integration in /integrations before opening PRs.",
    }, { status: 503 });
  }

  const language = draft.adaptedLanguage || draft.originalLanguage || "txt";
  const content = draft.adaptedLogic || draft.originalLogic || "";
  if (content.trim().length === 0) {
    return NextResponse.json({ error: "draft has no detection logic to publish" }, { status: 400 });
  }

  const filePath = filePathOverride || defaultPath(draft.id, draft.title, language);
  const commitMessage = `Add draft detection: ${draft.title}`;
  const prTitle = `[Rule Workspace] ${draft.title}`;
  const prBody = [
    `**Rule Workspace draft** \`${draft.id}\``,
    "",
    draft.notes ? `> ${draft.notes.replace(/\n/g, "\n> ")}` : "",
    "",
    `- **Source provenance:** ${draft.sourceName || "(authored from scratch)"} (\`${draft.sourceTable ?? "n/a"}\`)`,
    `- **Original language:** ${draft.originalLanguage || "n/a"}`,
    `- **Adapted language:** ${draft.adaptedLanguage || "n/a"}`,
    draft.conversionTarget ? `- **Sigma CLI target:** ${draft.conversionTarget} (${draft.conversionToolVersion || "version unknown"})` : "",
    "",
    "_Generated by the Detection Platform Rule Workspace._",
  ].filter(Boolean).join("\n");

  let pr;
  try {
    pr = await pushFileToBranchAndCreatePR(
      creds.token,
      owner,
      repo,
      filePath,
      content,
      commitMessage,
      prTitle,
      prBody,
      baseBranch || "main",
    );
  } catch (e: any) {
    await logWorkspaceAudit({
      action: "draft.pr_open",
      targetType: "draft",
      targetId: id,
      details: { owner, repo, filePath },
      success: false,
      errorMessage: e?.message || String(e),
    });
    return NextResponse.json({ error: e?.message || "PR creation failed" }, { status: 502 });
  }

  const updated = await prisma.ruleDraft.update({
    where: { id },
    data: {
      status: "pr_open",
      prNumber: pr.prNumber,
      prUrl: pr.prUrl,
      prBranch: pr.branchName,
      prRepo: `${owner}/${repo}`,
    },
  });

  await logWorkspaceAudit({
    action: "draft.pr_open",
    targetType: "draft",
    targetId: id,
    details: { owner, repo, filePath, prNumber: pr.prNumber, prUrl: pr.prUrl },
  });

  return NextResponse.json({
    ok: true,
    draft: updated,
    pr: {
      number: pr.prNumber,
      url: pr.prUrl,
      branch: pr.branchName,
      fileUrl: pr.fileUrl,
    },
  });
}
