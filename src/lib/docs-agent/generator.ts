// ─── Main Generator ───────────────────────────────────────────────

export function generateDocs(analysis: ProjectAnalysis): string[] {
  const files: string[] = [];

  const docs: [string, (a: ProjectAnalysis) => string][] = [
    ["index.md", generateIndex],
    ["architecture.md", generateArchitecture],
    ["api-reference.md", generateAPIReference],
    ["routes-map.md", generateRoutesMap],
    ["data-flows.md", generateDataFlows],
    ["service-map.md", generateServiceMap],
    ["components.md", generateComponentCatalog],
    ["types.md", generateTypeSystem],
    ["dependencies.md", generateDependencies],
  ];

  for (const [filename, generator] of docs) {
    write(filename, generator(analysis));
    files.push(filename);
  }

  // Write raw analysis JSON for programmatic access
  write("analysis.json", JSON.stringify(analysis, null, 2));
  files.push("analysis.json");

  return files;
}
