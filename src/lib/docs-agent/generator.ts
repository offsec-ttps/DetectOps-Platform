// ─── API Reference ────────────────────────────────────────────────

function generateAPIReference(a: ProjectAnalysis): string {
  const grouped = new Map<string, APIEndpoint[]>();
  for (const ep of a.apiEndpoints) {
    const group = ep.route.split("/").slice(0, 4).join("/");
    if (!grouped.has(group)) grouped.set(group, []);
    grouped.get(group)!.push(ep);
  }

  let md = `# API Reference

> Auto-generated by docs-agent on ${new Date(a.timestamp).toLocaleString()}

## Endpoints Summary

| Method | Route | Description | File |
|--------|-------|-------------|------|
`;
  for (const ep of a.apiEndpoints) {
    md += `| \`${ep.method}\` | \`${ep.route}\` | ${ep.description} | \`${ep.filePath}\` |\n`;
  }

  md += `\n## Endpoint Details\n`;

  for (const [group, endpoints] of grouped) {
    md += `\n### ${group}\n\n`;
    for (const ep of endpoints) {
      md += `#### \`${ep.method} ${ep.route}\`\n\n`;
      md += `- **File:** \`${ep.filePath}\`\n`;
      md += `- **Description:** ${ep.description}\n`;
      if (ep.queryParams && ep.queryParams.length > 0) {
        md += `- **Query Parameters:**\n`;
        for (const p of ep.queryParams) {
          md += `  - \`${p}\`\n`;
        }
      }
      md += `\n`;
    }
  }

  // API connectivity diagram
  md += `## API Connectivity\n\n\`\`\`mermaid\ngraph LR\n`;
  for (const ep of a.apiEndpoints) {
    const node = ep.route.replace(/[/:]/g, "_").replace(/^_/, "");
    md += `    ${node}["${ep.method} ${ep.route}"]\n`;
  }
  md += `\`\`\`\n`;

  return md;
}

// ─── Routes Map ───────────────────────────────────────────────────

function generateRoutesMap(a: ProjectAnalysis): string {
  const pages = a.routes.filter((r) => r.type === "page");
  const apis = a.routes.filter((r) => r.type === "api");
  const layouts = a.routes.filter((r) => r.type === "layout");

  let md = `# Routes Map

> Auto-generated by docs-agent on ${new Date(a.timestamp).toLocaleString()}

## Pages (${pages.length})

| Route | File | Dynamic | Params |
|-------|------|---------|--------|
`;
  for (const r of pages) {
    md += `| \`${r.path}\` | \`${r.filePath}\` | ${r.isDynamic ? "Yes" : "No"} | ${r.params?.join(", ") || "—"} |\n`;
  }

  md += `\n## API Routes (${apis.length})\n\n`;
  md += `| Route | Methods | File | Dynamic |\n|-------|---------|------|---------|\n`;
  for (const r of apis) {
    md += `| \`${r.path}\` | ${r.methods?.map((m) => `\`${m}\``).join(", ") || "—"} | \`${r.filePath}\` | ${r.isDynamic ? "Yes" : "No"} |\n`;
  }

  md += `\n## Layouts (${layouts.length})\n\n`;
  for (const r of layouts) {
    md += `- \`${r.filePath}\`\n`;
  }

  // Route tree diagram
  md += `\n## Route Tree\n\n\`\`\`mermaid\ngraph TD\n`;
  md += `    root["/"]\n`;
  const seen = new Set<string>();
  for (const r of pages) {
    const segments = r.path.split("/").filter(Boolean);
    let parent = "root";
    let accumulated = "";
    for (let i = 0; i < segments.length; i++) {
      accumulated += "_" + segments[i].replace(/:/g, "");
      const nodeId = `p${accumulated}`;
      if (!seen.has(nodeId)) {
        seen.add(nodeId);
        const label = segments[i].startsWith(":") ? `[${segments[i]}]` : segments[i];
        md += `    ${nodeId}["/${label}"]\n`;
        md += `    ${parent} --> ${nodeId}\n`;
      }
      parent = nodeId;
    }
  }
  md += `\`\`\`\n`;

  return md;
}

// ─── Data Flow Diagram ───────────────────────────────────────────

function generateDataFlows(a: ProjectAnalysis): string {
  let md = `# Data Flow Diagram

> Auto-generated by docs-agent on ${new Date(a.timestamp).toLocaleString()}

## Page → API → Database Flows

\`\`\`mermaid
graph LR
`;

  const nodeIds = new Map<string, string>();
  let counter = 0;
  function nodeId(name: string): string {
    if (!nodeIds.has(name)) {
      nodeIds.set(name, `n${counter++}`);
    }
    return nodeIds.get(name)!;
  }

  // Group by type for subgraphs
  const pages = a.dataFlows.filter((f) => f.from.startsWith("Page"));
  const apiToDb = a.dataFlows.filter((f) => f.from.startsWith("API") && f.to.startsWith("DB"));

  if (pages.length > 0) {
    md += `    subgraph Pages\n`;
    for (const f of pages) {
      const id = nodeId(f.from);
      md += `        ${id}["${f.from}"]\n`;
    }
    md += `    end\n`;
  }

  const apiNodes = new Set([...pages.map((f) => f.to), ...apiToDb.map((f) => f.from)]);
  if (apiNodes.size > 0) {
    md += `    subgraph APIs\n`;
    for (const n of apiNodes) {
      md += `        ${nodeId(n)}["${n}"]\n`;
    }
    md += `    end\n`;
  }

  const dbNodes = new Set(apiToDb.map((f) => f.to));
  if (dbNodes.size > 0) {
    md += `    subgraph Database\n`;
    for (const n of dbNodes) {
      md += `        ${nodeId(n)}[("${n}")]\n`;
    }
    md += `    end\n`;
  }

  for (const f of a.dataFlows) {
    md += `    ${nodeId(f.from)} -->|"${f.label}"| ${nodeId(f.to)}\n`;
  }

  md += `\`\`\`\n`;

  // Table form
  md += `\n## All Data Flows\n\n| From | To | Label |\n|------|----|---------|\n`;
  for (const f of a.dataFlows) {
    md += `| ${f.from} | ${f.to} | ${f.label} |\n`;
  }

  return md;
}

// ─── Component Catalog ────────────────────────────────────────────

function generateComponentCatalog(a: ProjectAnalysis): string {
  const byCategory = new Map<string, typeof a.components>();
  for (const c of a.components) {
    if (!byCategory.has(c.category)) byCategory.set(c.category, []);
    byCategory.get(c.category)!.push(c);
  }

  let md = `# Component Catalog

> Auto-generated by docs-agent on ${new Date(a.timestamp).toLocaleString()}

## Summary

| Category | Count |
|----------|-------|
`;
  for (const [cat, comps] of byCategory) {
    md += `| ${cat} | ${comps.length} |\n`;
  }

  for (const [cat, comps] of byCategory) {
    md += `\n## ${cat.charAt(0).toUpperCase() + cat.slice(1)} Components\n\n`;
    md += `| Component | File | Exports |\n|-----------|------|---------|\n`;
    for (const c of comps) {
      md += `| **${c.name}** | \`${c.filePath}\` | ${c.exports.join(", ") || "—"} |\n`;
    }
  }

  // Component dependency diagram
  md += `\n## Component Dependencies\n\n\`\`\`mermaid\ngraph TD\n`;
  for (const c of a.components) {
    const id = c.name.replace(/[^a-zA-Z0-9]/g, "");
    for (const dep of c.dependencies) {
      if (dep.includes("/ui/")) {
        const depName = dep.split("/").pop()?.replace(/\.\w+$/, "") || dep;
        md += `    ${id}["${c.name}"] --> ${depName.replace(/[^a-zA-Z0-9]/g, "")}["${depName}"]\n`;
      }
    }
  }
  md += `\`\`\`\n`;

  return md;
}

// ─── Type System ──────────────────────────────────────────────────

function generateTypeSystem(a: ProjectAnalysis): string {
  const byKind = new Map<string, typeof a.types>();
  for (const t of a.types) {
    if (!byKind.has(t.kind)) byKind.set(t.kind, []);
    byKind.get(t.kind)!.push(t);
  }

  let md = `# Type System Reference

> Auto-generated by docs-agent on ${new Date(a.timestamp).toLocaleString()}

## Summary

| Kind | Count | Exported |
|------|-------|----------|
`;
  for (const [kind, types] of byKind) {
    md += `| ${kind} | ${types.length} | ${types.filter((t) => t.exported).length} |\n`;
  }

  for (const [kind, types] of byKind) {
    md += `\n## ${kind.charAt(0).toUpperCase() + kind.slice(1)}s (${types.length})\n\n`;
    md += `| Name | Exported | Line |\n|------|----------|------|\n`;
    for (const t of types) {
      md += `| \`${t.name}\` | ${t.exported ? "Yes" : "No"} | ${t.line} |\n`;
    }
  }

  return md;
}

