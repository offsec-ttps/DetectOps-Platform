/**
 * UseCase → Atomic Red Team YAML.
 *
 * ART organises tests inside a `technique` block keyed by `attack_technique`.
 * Each technique block carries N `atomic_tests`. We emit a single technique
 * block per distinct `techniqueId` in the UseCase, with one `atomic_tests`
 * entry per UseCaseStep of `kind="atomic"`.
 *
 * Non-atomic steps (purplesharp / stratus / manual) are skipped — the
 * exporter returns a warning so the caller can surface a hint.
 */

import * as yaml from "js-yaml";
import { createHash } from "node:crypto";
import type { AtomicYamlInput, StepParameters } from "@/lib/use-cases/types";

export interface AtomicExportInput {
  useCase: {
    id: string;
    name: string;
    description: string;
  };
  steps: Array<{
    id: string;
    kind: string;
    refId: string;
    techniqueId: string;
    displayName: string;
    parameters: string;                     // JSON string
    expectedSignal: string;
    notes: string;
  }>;
}

export interface ExporterResult {
  body: string;
  checksum: string;
  skippedKinds: Record<string, number>;     // { purplesharp: 2, stratus: 1 }
  emittedTests: number;
}

function safeParseParams(s: string): StepParameters {
  try { return JSON.parse(s) as StepParameters; } catch { return {}; }
}

function sha256Short(s: string): string {
  return createHash("sha256").update(s, "utf8").digest("hex").slice(0, 16);
}

/** Build the technique-block YAML body. */
export function exportAtomicYaml(input: AtomicExportInput): ExporterResult {
  const atomicSteps = input.steps.filter((s) => s.kind === "atomic");
  const skipped: Record<string, number> = {};
  for (const s of input.steps.filter((s) => s.kind !== "atomic")) {
    skipped[s.kind] = (skipped[s.kind] || 0) + 1;
  }

  if (atomicSteps.length === 0) {
    const body = `# ${input.useCase.name}\n# No ART steps found in this use case.\n`;
    return { body, checksum: sha256Short(body), skippedKinds: skipped, emittedTests: 0 };
  }

  // Group atomic steps by techniqueId so we emit one block per technique.
  const byTechnique = new Map<string, typeof atomicSteps>();
  for (const s of atomicSteps) {
    const tid = s.techniqueId || "T0000";
    if (!byTechnique.has(tid)) byTechnique.set(tid, []);
    byTechnique.get(tid)!.push(s);
  }

  const blocks: Array<Record<string, unknown>> = [];
  for (const [techniqueId, group] of byTechnique) {
    const techniqueName = group[0].displayName || techniqueId;
    const tests = group.map((s) => {
      const params = safeParseParams(s.parameters);
      const a = params.atomic || {};
      const y: AtomicYamlInput = a.yaml || {
        attack_technique: techniqueId,
        display_name: techniqueName,
        name: s.displayName,
        description: s.notes || techniqueName,
        supported_platforms: ["windows"],
        input_arguments: [],
        dependency_executor_name: "",
        dependencies: [],
        executor: { name: "powershell", command: null, cleanup_command: null, elevation_required: false },
        auto_generated_guid: null,
      };
      // ART YAML field layout for one test
      const test: Record<string, unknown> = {
        name: y.name || s.displayName,
        auto_generated_guid: y.auto_generated_guid || undefined,
        description: y.description || "",
        supported_platforms: y.supported_platforms?.length ? y.supported_platforms : ["windows"],
      };
      if (y.input_arguments?.length) {
        // ART expects input_arguments as an object: { <name>: { description, type, default } }
        test.input_arguments = Object.fromEntries(
          y.input_arguments.map((a) => [
            a.name,
            { description: a.description || "", type: a.type, default: a.default || "" },
          ]),
        );
      }
      if (y.dependency_executor_name) test.dependency_executor_name = y.dependency_executor_name;
      if (y.dependencies?.length) test.dependencies = y.dependencies;
      test.executor = {
        name: y.executor.name || "powershell",
        elevation_required: !!y.executor.elevation_required,
        ...(y.executor.command ? { command: y.executor.command } : {}),
        ...(y.executor.cleanup_command ? { cleanup_command: y.executor.cleanup_command } : {}),
        ...(y.executor.steps ? { steps: y.executor.steps } : {}),
      };
      return test;
    });

    blocks.push({
      attack_technique: techniqueId,
      display_name: techniqueName,
      atomic_tests: tests,
    });
  }

  // ART YAMLs are single technique per file; we emit one document per block,
  // separated by `---` so the user can split if they want.
  const docs = blocks.map((b) =>
    yaml.dump(b, { lineWidth: 100, noRefs: true, quotingType: '"' }),
  ).join("\n---\n");

  const header =
    `# Atomic Red Team playbook — generated by DetectOps Use Case Builder\n` +
    `# UseCase: ${input.useCase.name} (${input.useCase.id})\n` +
    (input.useCase.description ? `# ${input.useCase.description.replace(/\n/g, " ")}\n` : "") +
    `\n`;

  const body = header + docs;
  return {
    body,
    checksum: sha256Short(body),
    skippedKinds: skipped,
    emittedTests: atomicSteps.length,
  };
}
