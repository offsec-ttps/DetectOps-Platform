/**
 * UseCase → Stratus Red Team portable shell script.
 *
 * Emits an idempotent bash script with three phases per attack: warmup,
 * detonate, cleanup. Phases per step come from `parameters.stratus.phases`;
 * default is `["warmup", "detonate"]` (cleanup left to operator).
 *
 * Non-stratus steps are skipped with warning counts.
 */

import { createHash } from "node:crypto";
import type { StepParameters } from "@/lib/use-cases/types";

export interface StratusExportInput {
  useCase: { id: string; name: string; description: string };
  steps: Array<{
    id: string; kind: string; refId: string; techniqueId: string;
    displayName: string; parameters: string;
    expectedSignal: string; notes: string;
  }>;
}

export interface StratusExportResult {
  body: string;
  checksum: string;
  skippedKinds: Record<string, number>;
  emittedAttacks: number;
}

function safeParseParams(s: string): StepParameters {
  try { return JSON.parse(s) as StepParameters; } catch { return {}; }
}

function sha256Short(s: string): string {
  return createHash("sha256").update(s, "utf8").digest("hex").slice(0, 16);
}

function bashEscape(s: string): string {
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$").replace(/`/g, "\\`")}"`;
}

export function exportStratusShell(input: StratusExportInput): StratusExportResult {
  const stratus = input.steps.filter((s) => s.kind === "stratus");
  const skipped: Record<string, number> = {};
  for (const s of input.steps.filter((s) => s.kind !== "stratus")) {
    skipped[s.kind] = (skipped[s.kind] || 0) + 1;
  }

  const ts = new Date().toISOString();
  const head =
    `#!/usr/bin/env bash\n` +
    `# Stratus Red Team playbook — generated by DetectOps Use Case Builder\n` +
    `# UseCase: ${input.useCase.name} (${input.useCase.id})\n` +
    (input.useCase.description ? `# ${input.useCase.description.replace(/\n/g, " ")}\n` : "") +
    `# Generated: ${ts}\n` +
    `# Requires the Stratus CLI (https://github.com/DataDog/stratus-red-team) and AWS/Azure/GCP creds in env.\n` +
    `\n` +
    `set -euo pipefail\n` +
    `command -v stratus >/dev/null || { echo "stratus CLI not found in PATH. See https://github.com/DataDog/stratus-red-team#installation" >&2; exit 127; }\n` +
    `LOG_DIR="$(mktemp -d -t stratus-XXXX)"\n` +
    `echo "stratus log dir: $LOG_DIR"\n\n`;

  if (stratus.length === 0) {
    const body = head + `# No Stratus steps in this use case.\n`;
    return { body, checksum: sha256Short(body), skippedKinds: skipped, emittedAttacks: 0 };
  }

  let body = head;
  let emitted = 0;
  for (let i = 0; i < stratus.length; i++) {
    const s = stratus[i];
    const params = safeParseParams(s.parameters);
    const phases = params.stratus?.phases?.length
      ? params.stratus.phases
      : (["warmup", "detonate"] as const);
    const attackId = s.refId || s.techniqueId || s.displayName;
    const label = bashEscape(`${i + 1}. ${s.displayName} (${attackId})`);

    body += `# ─── ${i + 1}. ${s.displayName} ───\n`;
    body += `echo ${label}\n`;
    if (s.expectedSignal) body += `echo "expected signal: ${s.expectedSignal.replace(/"/g, "\\\"")}"\n`;
    for (const phase of phases) {
      body += `stratus ${phase} ${bashEscape(attackId)} | tee "$LOG_DIR/${attackId}-${phase}.log"\n`;
    }
    body += `\n`;
    emitted++;
  }

  body += `echo "─── all stratus phases complete ───"\n`;
  body += `echo "logs saved to: $LOG_DIR"\n`;
  return {
    body,
    checksum: sha256Short(body),
    skippedKinds: skipped,
    emittedAttacks: emitted,
  };
}
